"""Pure-ASGI reverse proxy sub-application.

This module exposes :func:`create_reverse_proxy_app`, a factory that
builds a small ASGI app forwarding all incoming HTTP requests to an
upstream base URL (e.g. Prometheus or Alertmanager) and streaming the
upstream response back to the client.

Design goals:

* Byte-level pass-through for path / query / body / headers
* Strip hop-by-hop headers (RFC 2616 §13.5.1) and ``Host``
* Map connection errors to ``502 Bad Gateway``
* Map read / write timeouts to ``504 Gateway Timeout``
* Reuse a shared :class:`httpx.AsyncClient` from
  ``scope["app"].state.http_client`` when available
"""

import logging
from collections.abc import Awaitable, Callable

import httpx

logger = logging.getLogger(__name__)

# Hop-by-hop headers that MUST NOT be forwarded (RFC 2616 §13.5.1),
# plus ``Host`` which is regenerated by httpx based on the target URL.
_HOP_BY_HOP_HEADERS = frozenset([
    b"connection",
    b"keep-alive",
    b"proxy-authenticate",
    b"proxy-authorization",
    b"te",
    b"trailer",
    b"transfer-encoding",
    b"upgrade",
    b"host",
])

# Default timeouts (seconds). See design doc §5.4.
_DEFAULT_TIMEOUT = httpx.Timeout(
    connect=5.0,
    read=60.0,
    write=30.0,
    pool=5.0,
)

#: Maximum allowed request body size (bytes). The reverse proxy is
#: exposed to external clients; without a cap an attacker could send an
#: unbounded body and exhaust server memory (DoS). Prometheus /
#: Alertmanager request bodies (silence definitions, alert posts, etc.)
#: are typically well under 1 MB, so 10 MB is generous.
_MAX_BODY_SIZE = 10 * 1024 * 1024  # 10 MB


class _BodyTooLargeError(Exception):
    """Raised when the incoming request body exceeds ``_MAX_BODY_SIZE``."""


# ASGI type aliases for readability
Scope = dict
Message = dict
Receive = Callable[[], Awaitable[Message]]
Send = Callable[[Message], Awaitable[None]]


def _filter_request_headers(headers: list[tuple[bytes, bytes]]) -> dict:
    """Filter incoming headers, dropping hop-by-hop and Host.

    Args:
        headers: ASGI request headers list

    Returns:
        Dict of header name -> value safe to forward upstream.
    """
    out: dict[str, str] = {}
    for name, value in headers:
        if name.lower() in _HOP_BY_HOP_HEADERS:
            continue
        # httpx accepts both bytes and str; use latin-1 to preserve
        # arbitrary octets per HTTP spec.
        out[name.decode("latin-1")] = value.decode("latin-1")
    return out


def _filter_response_headers(
    headers: list[tuple[bytes, bytes]],
) -> list[tuple[bytes, bytes]]:
    """Filter upstream response headers, dropping hop-by-hop entries.

    Both ``Content-Length`` and ``Content-Encoding`` are dropped:

    * ``Content-Length`` — we re-frame the body through ASGI and the
      server (uvicorn) recomputes it from the actual payload.
    * ``Content-Encoding`` — httpx transparently decompresses gzip /
      deflate / br bodies when reading ``upstream_resp.content``. If we
      forwarded the upstream ``Content-Encoding: gzip`` header while
      sending the *decompressed* payload, the browser would attempt to
      gunzip a plain JSON body and fail with
      ``NS_ERROR_INVALID_CONTENT_ENCODING`` (Firefox) or a blank
      response (Chrome).

    Args:
        headers: Upstream response headers list

    Returns:
        Filtered headers safe to send to the downstream client.
    """
    drop = _HOP_BY_HOP_HEADERS | {b"content-length", b"content-encoding"}
    return [(n, v) for n, v in headers if n.lower() not in drop]


async def _read_request_body(receive: Receive) -> bytes:
    """Read the entire request body from ASGI receive channel.

    Buffers the body in memory with a hard cap of ``_MAX_BODY_SIZE``
    bytes. Prometheus / Alertmanager request bodies (silence definitions,
    alert posts, etc.) are typically small (<1 MB), so streaming is
    unnecessary here.

    Args:
        receive: ASGI receive callable

    Returns:
        Full request body bytes.

    Raises:
        _BodyTooLargeError: if the body exceeds ``_MAX_BODY_SIZE``.
    """
    chunks: list[bytes] = []
    total = 0
    while True:
        message = await receive()
        if message["type"] != "http.request":
            break
        chunk = message.get("body", b"")
        total += len(chunk)
        if total > _MAX_BODY_SIZE:
            raise _BodyTooLargeError(
                f"Request body exceeds {_MAX_BODY_SIZE} bytes"
            )
        chunks.append(chunk)
        if not message.get("more_body", False):
            break
    return b"".join(chunks)


async def _send_json_error(send: Send, status: int, detail: str) -> None:
    """Send a JSON error response.

    Args:
        send: ASGI send callable
        status: HTTP status code
        detail: Human-readable error detail
    """
    import json

    body = json.dumps({"detail": detail}).encode("utf-8")
    await send({
        "type": "http.response.start",
        "status": status,
        "headers": [
            (b"content-type", b"application/json"),
            (b"content-length", str(len(body)).encode("latin-1")),
        ],
    })
    await send({"type": "http.response.body", "body": body})


def create_reverse_proxy_app(
    service_name: str,
    target_base_url: str,
    timeout: httpx.Timeout | None = None,
):
    """Create an ASGI sub-application that reverse-proxies to upstream.

    Args:
        service_name: Human-readable name (used in logs and error msgs)
        target_base_url: Upstream base URL, e.g. ``http://127.0.0.1:9090``.
            Trailing slash is stripped.
        timeout: Optional custom :class:`httpx.Timeout`. Defaults to
            ``_DEFAULT_TIMEOUT``.

    Returns:
        An ASGI ``async def app(scope, receive, send)`` callable.
    """
    base = target_base_url.rstrip("/")
    _timeout = timeout or _DEFAULT_TIMEOUT

    async def proxy_app(scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            # Only HTTP is supported; lifespan/websocket are not proxied.
            await _send_json_error(
                send, 400, f"Unsupported scope type: {scope['type']}"
            )
            return

        method = scope["method"]
        # Starlette's Mount sets scope["root_path"] to the mount prefix
        # (e.g. "/v1/proxy/prometheus") and keeps scope["path"] as the
        # FULL original path (e.g. "/v1/proxy/prometheus/api/v1/query").
        # Strip the root_path prefix so the upstream URL is
        # "<base>/api/v1/query" rather than
        # "<base>/v1/proxy/prometheus/api/v1/query".
        full_path = scope.get("path", "/") or "/"
        root_path = scope.get("root_path", "") or ""
        if root_path and full_path.startswith(root_path):
            path = full_path[len(root_path) :] or "/"
        else:
            path = full_path
        query_string = scope.get("query_string", b"").decode("latin-1")
        url = f"{base}{path}"
        if query_string:
            url = f"{url}?{query_string}"

        headers = _filter_request_headers(scope.get("headers", []))
        try:
            body = await _read_request_body(receive)
        except _BodyTooLargeError as e:
            logger.warning(
                f"Reverse proxy '{service_name}' rejected oversized body "
                f"for {method} {url}: {e}"
            )
            await _send_json_error(send, 413, str(e))
            return

        # Resolve HTTP client: prefer the shared one stored on the main
        # FastAPI app state by the lifespan handler. Fall back to a
        # short-lived client when the proxy is exercised in isolation
        # (e.g. unit tests that build the sub-app directly).
        root_app = scope.get("app")
        client: httpx.AsyncClient | None = getattr(
            getattr(root_app, "state", None), "http_client", None
        )
        own_client: httpx.AsyncClient | None = None
        if client is None:
            own_client = httpx.AsyncClient(
                timeout=_timeout, follow_redirects=False
            )
            client = own_client

        try:
            try:
                upstream_resp = await client.request(
                    method,
                    url,
                    content=body if body else None,
                    headers=headers,
                )
            except httpx.TimeoutException as e:
                logger.warning(
                    f"Reverse proxy '{service_name}' timeout "
                    f"for {method} {url}: {e}"
                )
                await _send_json_error(send, 504, "Gateway timeout")
                return
            except httpx.TransportError as e:
                logger.warning(
                    f"Reverse proxy '{service_name}' transport error "
                    f"for {method} {url}: {e}"
                )
                await _send_json_error(
                    send, 502, f"Bad gateway: {type(e).__name__}: {e}"
                )
                return

            resp_headers = _filter_response_headers(
                list(upstream_resp.headers.raw)
            )
            resp_body = upstream_resp.content
            resp_headers.append((
                b"content-length",
                str(len(resp_body)).encode("latin-1"),
            ))
            await send({
                "type": "http.response.start",
                "status": upstream_resp.status_code,
                "headers": resp_headers,
            })
            await send({"type": "http.response.body", "body": resp_body})
        finally:
            if own_client is not None:
                await own_client.aclose()

    return proxy_app
